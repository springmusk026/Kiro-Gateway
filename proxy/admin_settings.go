// apiUpdateThinkingConfig 更新 thinking 配置
func (h *Handler) apiUpdateThinkingConfig(w http.ResponseWriter, r *http.Request) {
	var req struct {
		Suffix       string `json:"suffix"`
		OpenAIFormat string `json:"openaiFormat"`
		ClaudeFormat string `json:"claudeFormat"`
		Mode         string `json:"mode"`
		Budget       *int   `json:"budget"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		w.WriteHeader(400)
		json.NewEncoder(w).Encode(map[string]string{"error": "Invalid JSON"})
		return
	}

	// 验证格式
	validFormats := map[string]bool{"reasoning_content": true, "thinking": true, "think": true}
	if req.OpenAIFormat != "" && !validFormats[req.OpenAIFormat] {
		w.WriteHeader(400)
		json.NewEncoder(w).Encode(map[string]string{"error": "Invalid openaiFormat, must be: reasoning_content, thinking, or think"})
		return
	}
	if req.ClaudeFormat != "" && !validFormats[req.ClaudeFormat] {
		w.WriteHeader(400)
		json.NewEncoder(w).Encode(map[string]string{"error": "Invalid claudeFormat, must be: reasoning_content, thinking, or think"})
		return
	}

	if req.Mode != "" && req.Mode != "auto" && req.Mode != "always" && req.Mode != "never" {
		w.WriteHeader(400)
		json.NewEncoder(w).Encode(map[string]string{"error": "Invalid mode, must be: auto, always, or never"})
		return
	}
	if req.Budget != nil && *req.Budget != 0 && (*req.Budget < minThinkingBudget || *req.Budget > maxThinkingBudget) {
		w.WriteHeader(400)
		json.NewEncoder(w).Encode(map[string]string{"error": fmt.Sprintf("budget must be between %d and %d tokens (0 = default)", minThinkingBudget, maxThinkingBudget)})
		return
	}

	if err := config.UpdateThinkingConfig(req.Suffix, req.OpenAIFormat, req.ClaudeFormat); err != nil {
		w.WriteHeader(500)
		json.NewEncoder(w).Encode(map[string]string{"error": err.Error()})
		return
	}
	if req.Mode != "" || req.Budget != nil {
		cur := config.GetThinkingConfig()
		mode, budget := cur.Mode, cur.Budget
		if budget == config.DefaultThinkingBudget {
			budget = 0
		}
		if req.Mode != "" {
			mode = req.Mode
		}
		if req.Budget != nil {
			budget = *req.Budget
		}
		if err := config.UpdateThinkingPolicy(mode, budget); err != nil {
			w.WriteHeader(500)
			json.NewEncoder(w).Encode(map[string]string{"error": err.Error()})
			return
		}
	}

	json.NewEncoder(w).Encode(map[string]bool{"success": true})
}

